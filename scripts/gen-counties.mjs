// gen-counties.mjs — rebuild scripts/lib/counties.mjs from the data/*-baseline.json files.
// The results reader uses this list to match whatever county spelling a state's feed uses
// ("ST. CLAIR", "Saint Clair County", "DeKalb", "De Kalb") to the exact name the needle uses.
// Run after adding or rebuilding any baseline:  node scripts/gen-counties.mjs
import fs from "node:fs";
import path from "node:path";
import url from "node:url";
const ROOT = path.resolve(path.dirname(url.fileURLToPath(import.meta.url)), "..");
const out = {
  ME: ["Cumberland", "York", "Penobscot", "Kennebec", "Androscoggin", "Aroostook", "Hancock", "Oxford",
       "Somerset", "Knox", "Waldo", "Lincoln", "Sagadahoc", "Franklin", "Washington", "Piscataquis"],
};
for (const f of fs.readdirSync(path.join(ROOT, "data"))) {
  const m = f.match(/^([a-z]{2})-baseline\.json$/);
  if (!m) continue;
  const b = JSON.parse(fs.readFileSync(path.join(ROOT, "data", f), "utf8"));
  if (b.lean && Object.keys(b.lean).length) out[m[1].toUpperCase()] = Object.keys(b.lean);
}
fs.writeFileSync(path.join(ROOT, "scripts", "lib", "counties.mjs"),
  "// auto-generated by scripts/gen-counties.mjs from data/*-baseline.json — do not edit by hand\n" +
  "export default " + JSON.stringify(out) + ";\n");
console.log("counties.mjs:", Object.entries(out).map(([k, v]) => `${k} ${v.length}`).join(", "));
